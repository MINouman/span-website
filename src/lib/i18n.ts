// Locales (en, bn), default locale, UI string dictionary.
// English launches first; Bangla stays wired in from day one (spec §6).
// English URLs have no prefix (/projects). Bangla URLs are prefixed (/bn/projects).

export const locales = ['en', 'bn'] as const
export type Locale = (typeof locales)[number]
export const defaultLocale: Locale = 'en'

export function isLocale(value: string): value is Locale {
  return (locales as readonly string[]).includes(value)
}

/** Build a public URL path for a locale. `path` must start with "/". */
export function localePath(locale: Locale, path: string): string {
  if (locale === defaultLocale) return path
  return path === '/' ? `/${locale}` : `/${locale}${path}`
}

/** Strip the locale prefix from a browser path, so "/bn/projects" becomes "/projects". */
export function stripLocale(pathname: string): string {
  for (const locale of locales) {
    if (pathname === `/${locale}`) return '/'
    if (pathname.startsWith(`/${locale}/`)) return pathname.slice(locale.length + 1)
  }
  return pathname
}

